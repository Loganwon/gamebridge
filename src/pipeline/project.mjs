const json = value => JSON.stringify(value, null, 2) + '\n';
const refs = items => [...new Set(items.flatMap(item => item.requirementIds))];
function fail(code = 'INVALID_ADAPTER_PROJECT_INPUT') {
  throw Object.assign(new Error('Adapter draft input or output failed its local contract.'), { code });
}
function credentialGuards(options) {
  try {
    protocolObject(options, ['secrets'], 'adapter draft options');
    const secrets = protocolArray(options.secrets ?? [], 'credential guards', 64);
    if (Object.getPrototypeOf(secrets) !== Array.prototype || secrets.some(value => typeof value !== 'string' || value.length > 16384)) fail();
    return [...new Set(secrets.filter(Boolean))];
  } catch { fail(); }
}
function guard(text, secrets) {
  if (secrets.some(secret => text.includes(secret) || text.includes(JSON.stringify(secret).slice(1, -1)))) fail('ADAPTER_PROJECT_SECRET_DETECTED');
}

/** Generates local files only. It does not admit a host adapter, compile the
 * library, execute proposals, or turn a portable draft into a Mod project. */
export function makeAdapterProjectDraft(raw, options = {}) {
  try {
    protocolObject(raw, ['request', 'upstream', 'proposal'], 'adapter draft input');
    if (['request', 'upstream', 'proposal'].some(key => !Object.hasOwn(raw, key))) fail();
  } catch { fail(); }
  const secrets = credentialGuards(options);
  const checked = validatePipelineUpstream(raw.request, raw.upstream);
  const proposal = validateBehaviorProposal(raw.proposal, { request: checked.request, upstream: checked.upstream, secrets });
  const { request, plan, upstream } = checked, spec = proposal.spec;
  // Bind against the independently validated analysis; never use a model's own
  // claim about which requirements were present in the original task.
  const requirementIds = plan.requirements.map(item => item.id);
  guard(JSON.stringify({ request, upstream, proposal }), secrets);
  const review = upstream.find(item => item.role === 'independent-validation').analysis;
  const unresolvedRequirementIds = spec.unresolved.map(item => item.requirementId);
  const blockers = [
    { code: 'HOST_ADAPTER_REQUIRED', requirementIds: [...requirementIds], message: 'A separately admitted exact-version host generation adapter is required.' },
    { code: 'HOST_BINDINGS_UNVERIFIED', requirementIds: [...requirementIds], message: 'Host events, state and effects are not bound or verified by this draft.' },
    { code: 'SOURCE_BEHAVIOR_UNVERIFIED', requirementIds: [...requirementIds], message: 'Source behavior and feature fidelity require independent evidence.' },
    { code: 'SEMANTIC_COVERAGE_UNVERIFIED', requirementIds: [...requirementIds], message: 'Structure and requirement-ID coverage do not prove semantic completeness.' },
  ];
  if (unresolvedRequirementIds.length) blockers.push({ code: 'BEHAVIOR_REQUIREMENTS_UNRESOLVED', requirementIds: [...unresolvedRequirementIds], message: 'Unrepresented requirements remain mandatory and block complete acceptance.' });
  if (plan.assetNeeds.length) blockers.push({ code: 'ASSETS_UNVERIFIED', requirementIds: refs(plan.assetNeeds), message: 'Required resources, usage scope and mapping have not been verified.' });
  if (plan.interfaceNeeds.length) blockers.push({ code: 'HOST_INTERFACES_UNVERIFIED', requirementIds: refs(plan.interfaceNeeds), message: 'Requested interfaces are analysis proposals, not verified host APIs.' });
  const outside = plan.requirements.filter(item => item.disposition === 'out_of_scope').map(item => item.id);
  if (outside.length) blockers.push({ code: 'OUT_OF_SCOPE_REQUIREMENTS', requirementIds: outside, message: 'Requirements marked outside scope are retained and cannot count as implemented.' });
  const reviewGaps = [...new Set([...refs(review.issues), ...review.coverage.filter(item => item.assessment !== 'addressed_in_plan').map(item => item.requirementId)])];
  if (reviewGaps.length) blockers.push({ code: 'PLAN_REVIEW_GAPS', requirementIds: reviewGaps, message: 'Independent design-review issues and unclear or missing coverage remain unresolved.' });
  if (upstream.some(item => item.analysis.questions?.length)) blockers.push({ code: 'OPEN_ANALYSIS_QUESTIONS', requirementIds: [...requirementIds], message: 'Open analysis questions require clarification or evidence.' });

  const bindingRequirements = {
    schemaVersion: 1, scope: 'unbound-host-adapter-contract',
    hostGame: request.hostGame, sourceGame: request.sourceGame,
    hostVersion: request.hostVersion, sourceVersion: request.sourceVersion,
    hostAdapter: null, semanticCompleteness: false,
    requirements: plan.requirements.map(requirement => {
      const transitions = spec.transitions.filter(item => item.requirementIds.includes(requirement.id));
      const eventIds = new Set(transitions.map(item => item.event));
      const unresolved = spec.unresolved.filter(item => item.requirementId === requirement.id);
      return {
        requirement: { ...requirement },
        representation: { scope: 'state-data-only', transitionIds: transitions.map(item => item.id), unresolved },
        hostEvents: { status: 'unbound', events: spec.events.filter(item => eventIds.has(item.id)), instruction: 'Map real host inputs or events; do not synthesize evidence.' },
        hostState: { status: 'unbound', states: [...new Set(transitions.flatMap(item => [item.from, item.to]))], variables: structuredClone(spec.variables) },
        hostEffects: { status: 'unbound', instruction: 'Implement the full original requirement through permitted host interfaces. State-machine transitions alone do not implement its effects.' },
        resources: { status: 'unverified', needs: plan.assetNeeds.filter(item => item.requirementIds.includes(requirement.id)) },
        interfaces: { status: 'unverified', needs: plan.interfaceNeeds.filter(item => item.requirementIds.includes(requirement.id)) },
        sourceFidelity: { status: 'unverified' }, acceptance: { status: 'not_run' },
      };
    }),
    review: structuredClone(review),
    analysisQuestions: upstream.map(item => ({ role: item.role, questions: [...(item.analysis.questions ?? [])], limitations: [...item.analysis.limitations] })),
    proposal: { summary: proposal.summary, assumptions: [...proposal.assumptions], limitations: [...proposal.limitations] },
    blockers: structuredClone(blockers), realModBuild: 'not_run', game: 'not_run', readyToInstall: false,
  };
  const contents = {
    'Behavior.g.cs': emitCSharpBehavior(spec, { requirementIds }), 'HostBridge.g.cs': BRIDGE,
    'GameBridge.AdapterDraft.csproj': PROJECT,
    'NuGet.Config': '<configuration><packageSources><clear/></packageSources></configuration>\n',
    'request.json': json(request), 'analysis.json': json({ schemaVersion: 1, scope: 'unverified-analysis-context', upstream }),
    'behavior.spec.json': json(spec), 'binding-requirements.json': json(bindingRequirements), 'README.md': README,
  };
  const files = ADAPTER_DRAFT_FILES.map(file => ({ path: file, content: contents[file], mediaType: file.endsWith('.json') ? 'application/json' : 'text/plain' }));
  if (files.length > ARTIFACT_LIMITS.maxFiles || files.some(file => Buffer.byteLength(file.content) > ARTIFACT_LIMITS.maxFileBytes) ||
      files.reduce((total, file) => total + Buffer.byteLength(file.content), 0) > ARTIFACT_LIMITS.maxTotalBytes) fail('ADAPTER_PROJECT_LIMIT');
  for (const file of files) guard(file.content, secrets);
  return { files, metadata: { scope: 'adapter-project-draft', filePaths: [...ADAPTER_DRAFT_FILES], requirementIds: [...requirementIds],
    unresolvedRequirementIds: [...unresolvedRequirementIds], hostBindingStatus: 'blocked', blockers,
    semanticCompleteness: false, realModBuild: 'not_run', game: 'not_run', readyToInstall: false } };
}
