import { BEHAVIOR_LIMITS, validateBehaviorSpec } from './spec.mjs';

// Contract identifiers are ASCII; JSON string quoting is a compatible Squirrel
// string literal for this restricted alphabet. No caller-provided source is used.
const quoted = value => JSON.stringify(value);
function expression(raw) {
  if (raw.op === 'literal') return String(raw.value);
  if (raw.op === 'variable') return `variables[${quoted(raw.id)}]`;
  if (raw.op === 'event') return `inputs[${quoted(raw.id)}]`;
  const args = raw.args.map(expression);
  const binary = { eq: '==', ne: '!=', gt: '>', gte: '>=', lt: '<', lte: '<=', and: '&&', or: '||' };
  if (binary[raw.op]) return `(${args[0]} ${binary[raw.op]} ${args[1]})`;
  if (raw.op === 'not') return `(!${args[0]})`;
  if (raw.op === 'add') return `_numeric(${args[0]} + ${args[1]})`;
  if (raw.op === 'sub') return `_numeric(${args[0]} - ${args[1]})`;
  return `_${raw.op}(${args[0]}, ${args[1]})`;
}

/**
 * Emits a deterministic, host-neutral Squirrel 3 data machine. This grants no
 * file, command, game API or registration authority. It is not an OS sandbox.
 * Its class must be compiled and verified in the exact target VM before use.
 */
export function emitSquirrelBehavior(raw, options = {}) {
  const spec = validateBehaviorSpec(raw, options);
  const lines = [
    '// Generated by GameBridge BehaviorSpec v1. Host-neutral data execution.',
    'local GameBridgeBehaviorMachine = class {',
    '  state = null;',
    '  variables = null;',
    '  constructor() {',
    `    state = ${quoted(spec.initialState)};`,
    '    variables = {};',
    ...spec.variables.map(item => `    variables[${quoted(item.id)}] <- ${item.initial};`),
    '  }',
    `  function _numeric(value) { if (::type(value) != "integer" || value < -${BEHAVIOR_LIMITS.numeric} || value > ${BEHAVIOR_LIMITS.numeric}) throw "BEHAVIOR_ARITHMETIC_BOUNDS"; return value; }`,
    '  function _min(left, right) { return left < right ? left : right; }',
    '  function _max(left, right) { return left > right ? left : right; }',
    '  function _result(transitionId) {',
    '    local copied = {};',
    '    foreach (key, value in variables) copied[key] <- value;',
    '    return { state = state, variables = copied, transitionId = transitionId };',
    '  }',
    '  function snapshot() { return _result(null); }',
    '  function step(eventId, fields) {',
    '    if (::type(eventId) != "string" || ::type(fields) != "table") throw "INVALID_BEHAVIOR_EVENT";',
    '    local inputs = {};',
    '    local count = 0;',
    '    switch (eventId) {',
  ];
  for (const event of spec.events) {
    lines.push(`      case ${quoted(event.id)}:`, '        foreach (key, value in fields) {',
      `          if (++count > ${event.fields.length} || ::type(key) != "string" || ::type(value) != "integer") throw "INVALID_BEHAVIOR_EVENT";`);
    if (event.fields.length === 0) lines.push('          throw "INVALID_BEHAVIOR_EVENT";');
    else {
      event.fields.forEach((field, index) => lines.push(
        `          ${index ? 'else ' : ''}if (key == ${quoted(field.id)}) {`,
        `            if (value < ${field.min} || value > ${field.max}) throw "INVALID_BEHAVIOR_EVENT";`,
        '          }',
      ));
      lines.push('          else throw "INVALID_BEHAVIOR_EVENT";', '          inputs[key] <- value;');
    }
    lines.push('        }', `        if (count != ${event.fields.length}) throw "INVALID_BEHAVIOR_EVENT";`, '        break;');
  }
  lines.push('      default: throw "INVALID_BEHAVIOR_EVENT";', '    }');
  const sorted = [...spec.transitions].sort((a, b) => a.priority - b.priority || a.id.localeCompare(b.id));
  for (const transition of sorted) {
    lines.push(`    if (state == ${quoted(transition.from)} && eventId == ${quoted(transition.event)} && ${expression(transition.guard)}) {`);
    transition.updates.forEach((update, index) => {
      const definition = spec.variables.find(item => item.id === update.variable);
      lines.push(`      local updated_${index} = _numeric(${expression(update.value)});`,
        `      if (updated_${index} < ${definition.min} || updated_${index} > ${definition.max}) throw "BEHAVIOR_VARIABLE_BOUNDS";`);
    });
    transition.updates.forEach((update, index) => lines.push(`      variables[${quoted(update.variable)}] = updated_${index};`));
    lines.push(`      state = ${quoted(transition.to)};`, `      return _result(${quoted(transition.id)});`, '    }');
  }
  lines.push('    return _result(null);', '  }', '};', '');
  return lines.join('\n');
}
