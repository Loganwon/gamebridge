import { BEHAVIOR_LIMITS, validateBehaviorSpec } from './spec.mjs';

const quoted = value => JSON.stringify(value);
function expression(raw) {
  if (raw.op === 'literal') return typeof raw.value === 'boolean' ? String(raw.value) : `${raw.value}L`;
  if (raw.op === 'variable') return `variables[${quoted(raw.id)}]`;
  if (raw.op === 'event') return `inputs[${quoted(raw.id)}]`;
  const args = raw.args.map(expression);
  const binary = { eq: '==', ne: '!=', gt: '>', gte: '>=', lt: '<', lte: '<=', and: '&&', or: '||' };
  if (binary[raw.op]) return `(${args[0]} ${binary[raw.op]} ${args[1]})`;
  if (raw.op === 'not') return `(!${args[0]})`;
  if (raw.op === 'add') return `Numeric(${args[0]} + ${args[1]})`;
  if (raw.op === 'sub') return `Numeric(${args[0]} - ${args[1]})`;
  return `Math.${raw.op === 'min' ? 'Min' : 'Max'}(${args[0]}, ${args[1]})`;
}

/** Emits only locally defined C# templates and validated identifiers/literals. */
export function emitCSharpBehavior(raw, options = {}) {
  const spec = validateBehaviorSpec(raw, options), lines = [
    '// Generated by GameBridge BehaviorSpec v1. This is host-neutral behavior data execution.',
    '#nullable enable', 'using System;', 'using System.Collections.Generic;', '',
    'namespace GameBridge.Generated', '{',
    '  public sealed class StepResult', '  {',
    '    public string State { get; }', '    public IReadOnlyDictionary<string, long> Variables { get; }', '    public string? TransitionId { get; }',
    '    public StepResult(string state, IReadOnlyDictionary<string, long> variables, string? transitionId) { State = state; Variables = variables; TransitionId = transitionId; }',
    '  }', '  public sealed class BehaviorMachine', '  {',
    `    private string state = ${quoted(spec.initialState)};`, '    private readonly Dictionary<string, long> variables = new Dictionary<string, long>(StringComparer.Ordinal)', '    {',
    ...spec.variables.map(item => `      [${quoted(item.id)}] = ${item.initial}L,`), '    };',
    `    private static long Numeric(long value) { if (value < -${BEHAVIOR_LIMITS.numeric}L || value > ${BEHAVIOR_LIMITS.numeric}L) throw new InvalidOperationException("BEHAVIOR_ARITHMETIC_BOUNDS"); return value; }`,
    '    private StepResult Result(string? transitionId) { return new StepResult(state, new Dictionary<string, long>(variables, StringComparer.Ordinal), transitionId); }',
    '    public StepResult Snapshot() { return Result(null); }',
    '    public StepResult Step(string eventId, IReadOnlyDictionary<string, long> fields)', '    {',
    '      if (fields == null) throw new ArgumentException("INVALID_BEHAVIOR_EVENT");', '      var inputs = new Dictionary<string, long>(StringComparer.Ordinal);', '      switch (eventId)', '      {',
  ];
  for (const event of spec.events) {
    lines.push(`        case ${quoted(event.id)}:`);
    lines.push(`          if (fields.Count != ${event.fields.length}) throw new ArgumentException("INVALID_BEHAVIOR_EVENT");`);
    if (event.fields.length) lines.push(`          foreach (var key in fields.Keys) if (${event.fields.map(field => `key != ${quoted(field.id)}`).join(' && ')}) throw new ArgumentException("INVALID_BEHAVIOR_EVENT");`);
    event.fields.forEach((field, index) => lines.push(`          if (!fields.TryGetValue(${quoted(field.id)}, out var field_${spec.events.indexOf(event)}_${index}) || field_${spec.events.indexOf(event)}_${index} < ${field.min}L || field_${spec.events.indexOf(event)}_${index} > ${field.max}L) throw new ArgumentException("INVALID_BEHAVIOR_EVENT");`, `          inputs[${quoted(field.id)}] = field_${spec.events.indexOf(event)}_${index};`));
    lines.push('          break;');
  }
  lines.push('        default: throw new ArgumentException("INVALID_BEHAVIOR_EVENT");', '      }');
  const sorted = [...spec.transitions].sort((a, b) => a.priority - b.priority || a.id.localeCompare(b.id));
  for (const transition of sorted) {
    lines.push(`      if (state == ${quoted(transition.from)} && eventId == ${quoted(transition.event)} && ${expression(transition.guard)})`, '      {');
    transition.updates.forEach((update, index) => {
      const definition = spec.variables.find(item => item.id === update.variable);
      lines.push(`        long updated_${index} = Numeric(${expression(update.value)});`, `        if (updated_${index} < ${definition.min}L || updated_${index} > ${definition.max}L) throw new InvalidOperationException("BEHAVIOR_VARIABLE_BOUNDS");`);
    });
    transition.updates.forEach((update, index) => lines.push(`        variables[${quoted(update.variable)}] = updated_${index};`));
    lines.push(`        state = ${quoted(transition.to)};`, `        return Result(${quoted(transition.id)});`, '      }');
  }
  lines.push('      return Result(null);', '    }', '  }', '}', ''); return lines.join('\n');
}
